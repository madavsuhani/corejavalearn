
package pract1;

public class loops {

	public static void main(String[] args) {
		
		System.out.println("----------------While Loop----------------");
		
		int a=1;
		
		while(a<=10)
		{
			System.out.println(a);
			a++;
		}
		
		
		System.out.println("---------------Do-while Loop----------------");
		
		int b=1;
		
		do
		{
			System.out.println(b);
			b++;
		}
		while(b<=10);
		
		System.out.println("---------For loop--------------");
		
		for(int i=1; i<=10; i++)
		{
			System.out.println(i);
		}

	}
	

}
